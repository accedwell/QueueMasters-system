const { Pool } = require('pg');
const { hashPassword } = require('./security.cjs');
let pool;

function getPool() {
  if (!process.env.DATABASE_URL) throw new Error('DATABASE_URL is not configured.');
  if (!pool) pool = new Pool({
    connectionString: process.env.DATABASE_URL,
    max: 2, idleTimeoutMillis: 10000, connectionTimeoutMillis: 10000,
    options: '-c timezone=Africa/Johannesburg',
  });
  return pool;
}

async function transaction(db, run) {
  const client = await db.connect();
  try {
    await client.query('BEGIN');
    const value = await run(client);
    await client.query('COMMIT');
    return value;
  } catch (error) {
    await client.query('ROLLBACK');
    throw error;
  } finally { client.release(); }
}

async function initialize(db) {
  await transaction(db, async client => {
    // Cold starts may run concurrently. Serialize schema creation and founder seeding.
    await client.query('SELECT pg_advisory_xact_lock(782416039)');
    await client.query(`
      CREATE TABLE IF NOT EXISTS app_user (
        id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        username varchar(255) NOT NULL UNIQUE, password varchar(255) NOT NULL,
        role varchar(255) NOT NULL);
      CREATE TABLE IF NOT EXISTS vehicle (
        id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        plate_number varchar(255), car_model varchar(255), wash_type varchar(255),
        status varchar(255), is_paid boolean NOT NULL, amount_paid double precision NOT NULL,
        phone_number varchar(255), created_at timestamp DEFAULT (now() AT TIME ZONE 'Africa/Johannesburg'));
      CREATE TABLE IF NOT EXISTS sale_record (
        id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        plate_number varchar(255), wash_type varchar(255), amount double precision NOT NULL, date date);
      CREATE TABLE IF NOT EXISTS qm_session (
        token_hash varchar(64) PRIMARY KEY, user_id bigint NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
        expires_at timestamptz NOT NULL);
      CREATE INDEX IF NOT EXISTS qm_session_expiry ON qm_session(expires_at);
      CREATE TABLE IF NOT EXISTS qm_login_attempt (
        key varchar(64) PRIMARY KEY, attempts integer NOT NULL DEFAULT 1,
        started_at timestamptz NOT NULL DEFAULT now());
    `);
    const count = await client.query('SELECT count(*) FROM app_user');
    if (Number(count.rows[0].count) === 0) {
      await client.query('INSERT INTO app_user (username,password,role) VALUES ($1,$2,$3)',
        ['admin', await hashPassword(process.env.INITIAL_ADMIN_PASSWORD || 'admin@123'), 'ADMIN']);
    }
  });
}

module.exports = { getPool, initialize, transaction };
